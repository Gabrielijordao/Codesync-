'use strict';
const r = require('express').Router();
const {z} = require('zod');
const s = require('../validators/schemas');
const validate = require('../middlewares/validate');
const {requireAuth,allowRoles} = require('../middlewares/auth');
const c = require('../controllers/occurrence.controller');
r.use(requireAuth);
r.get('/',c.list);
r.get('/:id',validate(z.object({id:s.bigintId}),'params'),c.get);
r.post('/',validate(s.occurrenceCreate),c.create);
r.patch('/:id/analise',allowRoles('ADMIN'),validate(z.object({id:s.bigintId}),'params'),validate(s.occurrenceReview),c.review);
module.exports=r;
